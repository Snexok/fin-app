// Демо-подсказки под чатом («Можно купить кофе за 300?», «Наушники за 15 000?» …).
// Правило: показываем только пока чат пустой (пользователь ещё ничего не спросил в этой сессии); после первого вопроса строки нет.
// Чистые функции без React — покрыты тестами (tests/suggest-chips.test.ts).

/** Текст, который уходит в чат по нажатию подсказки (короткие «Наушники за 15 000?» → «Можно купить наушники за 15 000?»). */
export const chipQuery = (q: string) => (/^Можно|^Сколько/.test(q) ? q : "Можно купить " + q.charAt(0).toLowerCase() + q.slice(1));

/** Стартовые подсказки видны, пока в сессии нет ни одного сообщения пользователя (нажатие подсказки — тоже сообщение). */
export const showStarterChips = (msgs: readonly { me?: boolean }[]) => !msgs.some((m) => m.me);
